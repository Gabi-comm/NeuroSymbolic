"""Measured scale from a reference card in the photo.

Every millimetre the system prints is only as good as its mm-per-pixel figure.
The default, 4.357 mm/px, assumes the capture rule framed one 3.05 m lane. A
printed card with an ArUco marker of known size replaces that assumption with a
measurement for the photo in hand, and makes each reported width traceable to an
object visible in the image. The City Engineer has accepted the card in field
photos.

The marker is found in the bird's-eye view, after Inverse Perspective Mapping,
because that is the image the cracks are measured in. The warp maps a
trapezoid onto a square, so x and y can be scaled slightly differently; the
side length is taken as the square root of the marker's area, the geometric
mean of the two, and the stretch is reported so a badly skewed card can be seen.

Card: public/reference-card.svg (generated by tools/make_reference_card.py).
"""

from __future__ import annotations

import cv2
import numpy as np

ARUCO_DICTIONARY = cv2.aruco.DICT_4X4_50
REFERENCE_MARKER_ID = 7
# Black-square side of the printed marker, excluding the white quiet zone.
MARKER_SIDE_MM = 50.0

# Outside this range the detection is almost certainly not our card at a
# plausible distance, and trusting it would be worse than the default.
MIN_MM_PER_PX = 0.05
MAX_MM_PER_PX = 20.0

_detector = cv2.aruco.ArucoDetector(
    cv2.aruco.getPredefinedDictionary(ARUCO_DICTIONARY),
    cv2.aruco.DetectorParameters(),
)


def detect_reference_scale(img: np.ndarray) -> dict | None:
    """mm per pixel from the reference marker, or None when there is no card.

    Returns {"mm_per_px", "side_px", "stretch", "marker_id"}.
    """
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY) if img.ndim == 3 else img
    corners, ids, _ = _detector.detectMarkers(gray)
    if ids is None:
        return None

    for quad, marker_id in zip(corners, ids.flatten()):
        if int(marker_id) != REFERENCE_MARKER_ID:
            continue
        pts = quad.reshape(4, 2).astype(np.float64)
        area = abs(cv2.contourArea(pts.astype(np.float32)))
        if area <= 0:
            continue
        side_px = float(np.sqrt(area))
        edges = np.linalg.norm(pts - np.roll(pts, -1, axis=0), axis=1)
        mm_per_px = MARKER_SIDE_MM / side_px
        if not (MIN_MM_PER_PX <= mm_per_px <= MAX_MM_PER_PX):
            continue
        return {
            "mm_per_px": mm_per_px,
            "side_px": side_px,
            "stretch": float(edges.max() / edges.min()),
            "marker_id": int(marker_id),
        }

    return None
