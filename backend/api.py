def filter_overlapping_boxes(boxes, iou_threshold=0.4):
    """Non-maximum suppression. Returns the INDICES that survive.

    Indices (not a Boxes slice) because the caller must use the same positions
    to look up masks, confidences and class ids. Returning a slice is what let
    the previous version silently fall back to the unfiltered detections.
    """
    if boxes is None or len(boxes) == 0:
        return []

    boxes_xyxy = boxes.xyxy.cpu().numpy()
    scores = boxes.conf.cpu().numpy()

    indices = cv2.dnn.NMSBoxes(
        bboxes=[(int(x1), int(y1), int(x2 - x1), int(y2 - y1)) for x1, y1, x2, y2 in boxes_xyxy],
        scores=scores.tolist(),
        score_threshold=0.0,
        nms_threshold=iou_threshold,
    )

    if len(indices) == 0:
        return []

    return [int(i) for i in np.array(indices).flatten()]


def skeletonize_opencv(img):
    skel = np.zeros(img.shape, np.uint8)
    element = cv2.getStructuringElement(cv2.MORPH_CROSS, (3,3))

    while True:
        open_ = cv2.morphologyEx(img, cv2.MORPH_OPEN, element)
        temp = cv2.subtract(img, open_)
        eroded = cv2.erode(img, element)
        skel = cv2.bitwise_or(skel, temp)
        img = eroded.copy()

        if cv2.countNonZero(img) == 0:
            break

    return skel

def trace_cracks(image, crack_results, predictor, gsd, road_area_px):
    """Measure every surviving detection, then grade it.

    Two passes on purpose. Crack density is a property of the whole road segment,
    not of one detection, so no defect can be graded until every defect has been
    measured. The previous single-pass version graded each detection in isolation,
    which is why density -- a stated key feature -- was never computed at all.

    Returns (traced, debug_img, pure_skeleton, density_pct).
    """
    empty = ([], image.copy(), np.zeros(image.shape[:2], dtype=np.uint8), 0.0)

    if not crack_results or crack_results[0].masks is None:
        return empty

    keep_indices = filter_overlapping_boxes(crack_results[0].boxes)
    if len(keep_indices) == 0:
        return empty

    predictor.set_image(image)
    debug_img = image.copy()
    pure_skeleton = np.zeros(image.shape[:2], dtype=np.uint8)
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2GRAY)

    yolo_masks = crack_results[0].masks.data
    yolo_boxes = crack_results[0].boxes.xyxy.cpu().numpy().astype(int)
    confidences = crack_results[0].boxes.conf.cpu().numpy()
    class_ids = crack_results[0].boxes.cls.cpu().numpy().astype(int)
    names = crack_results[0].names

    # ---- Pass 1: segment, skeletonize, measure -----------------------------
    measured = []
    total_defect_px = 0

    for i in keep_indices:
        x1, y1, x2, y2 = yolo_boxes[i]
        label = names[class_ids[i]]

        masks, _, _ = predictor.predict(box=np.array([x1, y1, x2, y2]), multimask_output=False)
        sam_mask = masks[0].astype(np.uint8) * 255
        y_mask_raw = yolo_masks[i].cpu().numpy()
        y_mask_resized = cv2.resize(y_mask_raw, (image.shape[1], image.shape[0]))
        y_mask_binary = (y_mask_resized > 0.5).astype(np.uint8) * 255
        consensus_mask = cv2.bitwise_and(sam_mask, y_mask_binary)

        roi_fence = consensus_mask[y1:y2, x1:x2]
        roi_gray = gray[y1:y2, x1:x2]
        crack_pixels = cv2.adaptiveThreshold(
            cv2.GaussianBlur(roi_gray, (5, 5), 0), 255,
            cv2.ADAPTIVE_THRESH_GAUSSIAN_C, cv2.THRESH_BINARY_INV, 15, 5
        )
        valid_cracks = cv2.bitwise_and(crack_pixels, roi_fence)
        cleaned_cracks = cv2.morphologyEx(valid_cracks, cv2.MORPH_OPEN, np.ones((2, 2), np.uint8))

        mask_pixels = cv2.countNonZero(cleaned_cracks)
        if mask_pixels < 10:
            continue

        skel = skeletonize_opencv(cleaned_cracks)
        length_px = cv2.countNonZero(skel)

        # Mean width: mask area divided by centreline length, scaled to mm.
        width_mm = (mask_pixels / length_px * gsd) if length_px > 0 else 0.0

        if label in fuzzy_engine.AREA_DEFECT_LABELS:
            physical_metric = (mask_pixels * (gsd ** 2)) / 1_000_000.0
            unit, measurement_type = "sq.m", "Area"
        else:
            physical_metric = (length_px * gsd) / 1000.0
            unit, measurement_type = "m", "Length"

        total_defect_px += mask_pixels

        pure_skeleton[y1:y2, x1:x2] = cv2.bitwise_or(pure_skeleton[y1:y2, x1:x2], skel)
        debug_img[y1:y2, x1:x2][skel > 0] = [0, 0, 255]
        cv2.rectangle(debug_img, (x1, y1), (x2, y2), (0, 255, 0), 2)

        measured.append({
            "label": label,
            "measurement_type": measurement_type,
            "metric_value": physical_metric,
            "unit": unit,
            "width_mm": width_mm,
            "mask_pixels": mask_pixels,
            "confidence": float(confidences[i]),
            "box": (int(x1), int(y1)),
        })

    if not measured:
        return empty

    # ---- Crack density over the analysed road surface ----------------------
    density_pct = (total_defect_px / road_area_px * 100.0) if road_area_px > 0 else 0.0
    density_pct = float(min(density_pct, 100.0))

    # ---- Pass 2: symbolic reasoning ----------------------------------------
    traced = []
    for m in measured:
        grades = fuzzy_engine.evaluate(
            label=m["label"],
            width_mm=m["width_mm"],
            density_pct=density_pct,
            confidence=m["confidence"],
        )

        x1, y1 = m.pop("box")
        m.pop("mask_pixels")

        entry = {**m, **grades, "crack_density_pct": round(density_pct, 2)}
        # "severity" stays the headline field the UI already reads; it now carries
        # the fuzzy grade, with the two baselines alongside it for RQ3.
        entry["severity"] = grades["severity_fuzzy"]
        traced.append(entry)

        cv2.putText(
            debug_img, f"{m['label']} ({entry['severity']})",
            (x1, max(15, y1 - 5)), cv2.FONT_HERSHEY_SIMPLEX, 0.5, (0, 255, 0), 2,
        )

    return traced, debug_img, pure_skeleton, density_pct


def _summary_prose(context: str) -> str:
    """Ask the local model for the narrative paragraph only."""
    prompt = f"""You are a civil engineer writing the opening paragraph of a DPWH
road maintenance bulletin.

Measured findings:
{context}

Write two or three sentences describing the condition of this road segment.
Cite the measured crack density figure exactly as given. Refer to distress types
only by the exact names listed. Do not recommend any action, do not assign a
priority, and do not state any measurement that is not listed above.
Plain prose only: no headings, no bullet points, no asterisks."""

    try:
        response = requests.post(
            f"{OLLAMA_HOST}/api/generate",
            json={"model": OLLAMA_MODEL, "prompt": prompt, "stream": False},
            timeout=180,
        )
        response.raise_for_status()
        return response.json().get("response", "").strip()
    except requests.exceptions.ConnectionError:
        return (
            f"[Local LLM unavailable: could not reach Ollama at {OLLAMA_HOST}. "
            f"Start it with 'ollama serve' and ensure '{OLLAMA_MODEL}' is pulled.]"
        )
    except Exception as e:
        return f"[Error generating summary with local model: {e}]"


def generate_maintenance_bulletin(distresses, density_pct, ipm_applied):
    """Assemble a DPWH-style maintenance bulletin.

    Only the opening narrative comes from the language model. The intervention
    list and the priority level are rendered directly from the symbolic layer,
    because they are maintenance decisions: a 3B model asked to restate them
    duplicated one line per detection, mislabelled distress types, and on an
    earlier revision emitted two priority levels at once.

    Keeping the decisions deterministic also means the bulletin is auditable --
    every recommendation traces to fuzzy_engine.INTERVENTIONS rather than to a
    sampled token sequence.
    """
    header = "Road Segment Health Summary:"

    if not distresses:
        return (
            f"{header}\n"
            "No structural distress was detected in the analysed road surface. "
            f"Measured crack density is {density_pct:.2f} percent.\n\n"
            "Recommended Interventions:\n"
            "  None required at this time.\n\n"
            "Priority Level:\n"
            "  Routine - no distress detected; continue scheduled monitoring."
        )

    worst = worst_severity(distresses)
    priority = fuzzy_engine.priority_level(worst, density_pct)

    # Worst severity per distress type, with how many of each were found.
    by_type = {}
    for d in distresses:
        label, severity = d["label"], d["severity_fuzzy"]
        entry = by_type.setdefault(label, {"severity": severity, "count": 0})
        entry["count"] += 1
        if SEVERITY_RANK.get(severity, 0) > SEVERITY_RANK.get(entry["severity"], 0):
            entry["severity"] = severity

    ordered = sorted(
        by_type.items(), key=lambda kv: -SEVERITY_RANK.get(kv[1]["severity"], 0)
    )

    context_lines = [f"Crack density: {density_pct:.2f} percent of the road surface"]
    if not ipm_applied:
        context_lines.append(
            "Perspective correction could not be applied, so measurements are approximate"
        )
    for label, info in ordered:
        plural = "detection" if info["count"] == 1 else "detections"
        context_lines.append(
            f"{label}: {info['count']} {plural}, severity {info['severity']}"
        )

    summary = _summary_prose("\n".join(context_lines))

    interventions = "\n".join(
        f"  {label} - severity {info['severity']} - "
        f"{fuzzy_engine.intervention_for(label, info['severity'])} "
        f"({info['count']} detected)"
        for label, info in ordered
    )

    worst_types = ", ".join(
        label for label, info in ordered if info["severity"] == worst
    )
    justification = (
        f"  {priority} - driven by {worst} severity {worst_types} "
        f"at {density_pct:.2f} percent crack density."
    )

    return (
        f"{header}\n{summary}\n\n"
        f"Recommended Interventions:\n{interventions}\n\n"
        f"Priority Level:\n{justification}"
    )


@app.post("/analyze-road")
async def analyze_road(request: ImageRequest):
    try:
        print("--- Request received ---")

        # 1. Decode
        img = decode_base64_img(request.image_base64)
        if img is None:
            return JSONResponse(status_code=400, content={"message": "Invalid Image Data"})

        # 2. Privacy pass before anything is detected, measured or returned.
        img = apply_privacy_blur(img)

        # 3. Road detection, and the gate that depends on it
        road_results = road_model.predict(img, conf=0.25)

        frame_px = img.shape[0] * img.shape[1]
        road_px = road_mask_area_px(road_results, img.shape)
        road_coverage = (road_px / frame_px) if frame_px else 0.0

        if road_coverage < MIN_ROAD_COVERAGE:
            # Refuse rather than return a confident-looking assessment of
            # something that is not a road.
            print(f"Rejected: road coverage {road_coverage:.1%} < {MIN_ROAD_COVERAGE:.0%}")
            return JSONResponse(
                status_code=422,
                content={
                    "error": "no_road_detected",
                    "message": (
                        "No road surface was detected in this image. Upload a photo "
                        "of a road taken from chest height, about 2 m from the "
                        "defect, with the pavement filling most of the frame."
                    ),
                    "road_coverage_pct": round(road_coverage * 100, 2),
                    "required_coverage_pct": round(MIN_ROAD_COVERAGE * 100, 2),
                },
            )

        print(f"Road detected: {road_coverage:.1%} of frame.")

        # 4. Inverse Perspective Mapping
        print("Calculating bird's eye view...")
        bev_img, ipm_applied = get_birds_eye_view(img, road_results)

        # Denominator for crack density. A successful warp maps the road
        # trapezoid onto the whole frame, so the frame IS the road surface.
        # Without it, fall back to the detected road mask area so we do not
        # divide by sky and verge.
        if ipm_applied:
            road_area_px = bev_img.shape[0] * bev_img.shape[1]
        else:
            road_area_px = road_px
            print("IPM not applied; measurements are perspective-distorted.")

        # 5. Crack detection on the BEV
        print("Running crack detection...")
        crack_results = detect_crack(crack_model, bev_img)

        # 6. SAM tracing, metrics, and symbolic reasoning
        gsd = request.gsd_mm_px or DEFAULT_GSD_MM_PX
        print("Tracing with SAM, measuring, and grading...")
        traced_data, debug_img, skel, density_pct = trace_cracks(
            bev_img, crack_results, predictor, gsd, road_area_px
        )

        # 7. Encode the annotated image
        _, buffer = cv2.imencode(".jpg", debug_img)
        image_url = "data:image/jpeg;base64," + base64.b64encode(buffer).decode("utf-8")

        # 8. Maintenance bulletin from the local model
        print("Generating bulletin locally...")
        bulletin = generate_maintenance_bulletin(traced_data, density_pct, ipm_applied)

        return {
            "fileUrl": image_url,
            "distresses": traced_data if traced_data else [
                {"label": "Clear", "severity": "Low", "confidence": 1.0}
            ],
            "gemini_bulletin": bulletin,
            "overall_severity": worst_severity(traced_data),
            "gsd_mm_px": gsd,
            "crack_density_pct": round(density_pct, 2),
            "ipm_applied": ipm_applied,
            "road_coverage_pct": round(road_coverage * 100, 2),
            "privacy_blur_applied": PRIVACY_BLUR_ENABLED,
        }

    except Exception as e:
        print(f"CRITICAL ERROR: {e}")
        return JSONResponse(status_code=500, content={"message": str(e)})
