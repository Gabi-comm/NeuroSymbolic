SEVERITY_RANK = {"Low": 0, "Medium": 1, "High": 2}


def worst_severity(distresses):
    """Overall severity is the WORST distress found, never just the first one.

    The previous version returned traced_data[0]['severity'], so an image whose
    first detection was a hairline crack reported "Low" even when it also
    contained a high-severity pothole. For a maintenance prioritisation tool
    that is the one direction the error must never go.
    """
    if not distresses:
        return "Low"
    return max(
        (d.get("severity", "Low") for d in distresses),
        key=lambda sev: SEVERITY_RANK.get(sev, 0),
    )


# COCO class ids. People are blurred whole; vehicles only where plates sit.
PRIVACY_PERSON_CLASS = 0
PRIVACY_VEHICLE_CLASSES = {1, 2, 3, 5, 7}  # bicycle, car, motorcycle, bus, truck

# Plates sit low on a vehicle. Blurring the whole vehicle would often cover the
# road defect behind it, so only the bottom band is obscured.
PRIVACY_PLATE_BAND = 0.45


def _blur_region(img, x1, y1, x2, y2):
    x1, y1 = max(0, x1), max(0, y1)
    x2, y2 = min(img.shape[1], x2), min(img.shape[0], y2)
    if x2 <= x1 or y2 <= y1:
        return

    roi = img[y1:y2, x1:x2]
    # Kernel scales with region size so small faces are as unrecoverable as large ones.
    k = max(9, (min(roi.shape[:2]) // 4) | 1)
    img[y1:y2, x1:x2] = cv2.GaussianBlur(roi, (k, k), 0)


def apply_privacy_blur(img):
    """Obscure people and vehicle plates before any detection or storage.

    Runs on the raw upload, so no identifiable frame is ever measured, encoded
    into the returned annotated image, or written to the database.
    """
    if not PRIVACY_BLUR_ENABLED or privacy_model is None:
        return img

    try:
        results = privacy_model.predict(img, conf=0.35, verbose=False)
    except Exception as exc:
        print(f"Privacy blur failed: {exc}")
        return img

    if not results or results[0].boxes is None:
        return img

    boxes = results[0].boxes.xyxy.cpu().numpy().astype(int)
    classes = results[0].boxes.cls.cpu().numpy().astype(int)

    blurred = 0
    for (x1, y1, x2, y2), cls in zip(boxes, classes):
        if cls == PRIVACY_PERSON_CLASS:
            _blur_region(img, x1, y1, x2, y2)
            blurred += 1
        elif cls in PRIVACY_VEHICLE_CLASSES:
            band_top = int(y2 - (y2 - y1) * PRIVACY_PLATE_BAND)
            _blur_region(img, x1, band_top, x2, y2)
            blurred += 1

    if blurred:
        print(f"Privacy blur applied to {blurred} region(s).")
    return img


def road_mask_area_px(road_results, image_shape):
    """Road surface area in pixels, used as the density denominator when IPM fails."""
    if road_results[0].masks is None:
        return 0

    h, w = image_shape[:2]
    masks = road_results[0].masks.data.cpu().numpy()
    combined = np.zeros((masks.shape[1], masks.shape[2]), dtype=np.uint8)
    for m in masks:
        combined = np.maximum(combined, m)

    resized = cv2.resize((combined * 255).astype(np.uint8), (w, h))
    return int(cv2.countNonZero(resized))


def decode_base64_img(base64_str):
    """Converts a Base64 string from Next.js into a standard OpenCV image array."""
    try:
        header, encoded = base64_str.split(",", 1) if "," in base64_str else ("", base64_str)
        img_bytes = base64.b64decode(encoded)
        np_arr = np.frombuffer(img_bytes, np.uint8)
        return cv2.imdecode(np_arr, cv2.IMREAD_COLOR)
    except Exception as e:
        print(f"Error decoding image: {e}")
        return None


